"""Measure import scaling and repeated comparison; no workload execution or model API."""

from __future__ import annotations

import argparse
import hashlib
import importlib.metadata
import json
import math
import os
from pathlib import Path
import platform
import resource
import shutil
import statistics
import subprocess
import sys
import tempfile
import time
from datetime import datetime, timezone

from dynamo_diff.compare import compare_runs
from dynamo_diff.mcp_server import AnalysisTools
from dynamo_diff.store import Store

ROOT = Path(__file__).resolve().parents[1]
MIB = 1024 ** 2


def build_scaled_bundle(destination: Path, target_bytes: int) -> dict:
    """Replicate actual exported records/payloads with distinct frame namespaces.

    These are synthetic scale inputs, not additional PyTorch recordings. They
    preserve the template's event mix and payload sizes; no arbitrary padding.
    Source identity is intentionally repeated. Runtime matching is measured on
    the separately recorded edit pair, not on invented source correspondences.
    """
    template = ROOT / "fixtures/captures/multiple_guards/report"
    records = [json.loads(line) for line in (template / "raw.jsonl").read_text().splitlines()]
    header = records[0]
    globals_ = [record for record in records[1:] if "frame_id" not in record]
    framed = [record for record in records[1:] if "frame_id" in record]
    destination.mkdir(parents=True)
    bytes_written = 0
    copies = 0
    payload_count = 0
    metadata = destination / "raw.jsonl"
    with metadata.open("wb") as output:
        def emit(record: dict, prefix: str = "") -> None:
            nonlocal bytes_written, payload_count
            record = dict(record)
            name = record.get("payload_filename")
            if name:
                relative = f"{prefix}/{name}" if prefix else name
                dest = destination / relative
                if not dest.exists():
                    dest.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(template / name, dest)
                    bytes_written += dest.stat().st_size
                    payload_count += 1
                record["payload_filename"] = relative
            raw = json.dumps(record, separators=(",", ":"), ensure_ascii=False).encode() + b"\n"
            output.write(raw)
            bytes_written += len(raw)

        emit(header)
        for record in globals_:
            emit(record)
        while bytes_written < target_bytes:
            for record in framed:
                emit({**record, "frame_id": record["frame_id"] + copies * 1000}, f"copy-{copies:04d}")
            copies += 1
    actual = sum(p.stat().st_size for p in destination.rglob("*") if p.is_file())
    if actual != bytes_written:
        raise RuntimeError("Generated byte accounting disagrees with filesystem")
    return {"target_bytes": target_bytes, "actual_bytes": actual, "template_copies": copies,
            "expected_completed": copies * 3, "expected_successful_recompilations": copies * 2,
            "payload_files": payload_count, "metadata_bytes": metadata.stat().st_size,
            "metadata_sha256": hashlib.sha256(metadata.read_bytes()).hexdigest()}


def worker(report: Path, store_path: Path, expected: int) -> None:
    store = Store(store_path)
    start = time.perf_counter()
    capture = store.import_trace(report)
    elapsed = time.perf_counter() - start
    if capture.counts.completed != expected or capture.counts.confirmed_successful_recompilations != expected * 2 // 3:
        raise RuntimeError("Scaled input failed its known event count check")
    peak = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    peak_bytes = peak if sys.platform == "darwin" else peak * 1024
    normalized_bytes = (store.capture_dir(capture.id) / "capture.json").stat().st_size
    print(json.dumps({"import_seconds": elapsed, "process_peak_rss_bytes": peak_bytes,
        "normalized_capture_bytes": normalized_bytes, "completed": capture.counts.completed,
        "confirmed_successful_recompilations": capture.counts.confirmed_successful_recompilations}))


def summarize(runs: list[dict]) -> dict:
    return {"median_import_seconds": statistics.median(r["import_seconds"] for r in runs),
            "max_peak_rss_bytes": max(r["process_peak_rss_bytes"] for r in runs), "runs": runs}


def benchmark(args: argparse.Namespace) -> dict:
    if sys.platform not in ["darwin", "linux"]:
        raise SystemExit("Peak RSS measurement is supported on macOS/Linux only")
    if args.repeats < 3 or args.comparisons < 5:
        raise SystemExit("Use at least 3 import repetitions and 5 comparison repetitions")
    result = {"created_at": datetime.now(timezone.utc).isoformat(), "profile": "record-replication-v1",
        "platform": {"system": platform.system(), "release": platform.release(), "machine": platform.machine(),
                     "python": platform.python_version(), "pydantic": importlib.metadata.version("pydantic")},
        "method": {"input": "Synthetic replication of retained multiple_guards records and referenced payloads with distinct frame IDs; not newly recorded application workloads.",
            "imports": "Fresh worker process and empty content store per repetition. OS filesystem cache is not flushed; inputs are already generated locally.",
            "memory": "Process high-water RSS includes the Python interpreter and libraries; macOS bytes/Linux KiB converted to bytes.",
            "timing": "import_trace wall time excludes process startup, input generation, and upstream tlparse conversion. Parent process wall time is also retained.",
            "comparison": "Repeated warm comparisons of the actual recorded edit pair; normalized data and snapshots are read and checked on each call."},
        "sizes": [], "upstream_conversion": {"measured_here": False, "reason": "Saved exports are supplied; this benchmark does not run tlparse."}}
    with tempfile.TemporaryDirectory(prefix="dynamo-diff-benchmark-") as temporary:
        root = Path(temporary)
        for size in args.sizes:
            if size not in [10, 100]:
                raise SystemExit("The release baseline uses 10 and 100 MiB targets")
            bundle = root / f"input-{size}"
            description = build_scaled_bundle(bundle, size * MIB)
            runs = []
            for index in range(args.repeats):
                start = time.perf_counter()
                completed = subprocess.run([sys.executable, str(Path(__file__).resolve()), "--worker", str(bundle),
                    "--worker-store", str(root / f"store-{size}-{index}"), "--expected", str(description["expected_completed"])],
                    text=True, capture_output=True, timeout=180)
                if completed.returncode:
                    raise RuntimeError(completed.stderr)
                row = json.loads(completed.stdout)
                row["process_wall_seconds"] = time.perf_counter() - start
                runs.append(row)
                print(f"{size} MiB trial {index + 1}: import {row['import_seconds']:.3f}s, peak RSS {row['process_peak_rss_bytes']/MIB:.1f} MiB", file=sys.stderr, flush=True)
            result["sizes"].append({**description, **summarize(runs)})
        store = Store(root / "comparison-store")
        captures = [store.import_trace(ROOT / f"fixtures/captures/{name}/report", manifest_path=ROOT / f"fixtures/captures/{name}/manifest.json")
                    for name in ["edit_before", "edit_after"]]
        ids = [capture.id for capture in captures]
        compare_runs(store, *ids)  # warm-up is excluded and disclosed
        times = []
        for _ in range(args.comparisons):
            start = time.perf_counter()
            report = compare_runs(store, *ids)
            times.append(time.perf_counter() - start)
        full = json.dumps(report.model_dump(), ensure_ascii=False)
        initial = AnalysisTools(store, [ROOT / "fixtures/captures"]).compare_runs(*ids)
        result["comparison"] = {"fixture_pair": ["edit_before", "edit_after"], "warmup_calls": 1,
            "repetitions": len(times), "seconds": times, "median_seconds": statistics.median(times),
            "p95_seconds": sorted(times)[math.ceil(len(times) * .95) - 1],
            "full_json_chars": len(full), "full_json_utf8_bytes": len(full.encode()),
            "initial_mcp_json_chars": len(json.dumps(initial, ensure_ascii=False)), "functions": len(report.functions)}
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "benchmarks/results/import-baseline.json")
    parser.add_argument("--sizes", type=int, nargs="+", default=[10, 100])
    parser.add_argument("--repeats", type=int, default=3)
    parser.add_argument("--comparisons", type=int, default=20)
    parser.add_argument("--worker", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--worker-store", type=Path, help=argparse.SUPPRESS)
    parser.add_argument("--expected", type=int, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker:
        worker(args.worker, args.worker_store, args.expected)
        return
    if args.output.exists():
        raise SystemExit(f"Refusing to overwrite measurement: {args.output}")
    result = benchmark(args)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
